-- 0143 — ``space_join_requests.applicant_relay``: how the host answers an
-- "Ask to join" that came through a GFS from a household it never paired
-- with (v_84, ``socialhome/federation/gfs_join_request.py``).
--
-- Such a request is sealed to the host over the GFS relay. The host files it
-- as an ordinary pending request (the admins' queue, their bell); its answer,
-- days later, must go back sealed the same way — to the applicant household's
-- identity + key-wrap keys, through the GFS the request came in on. This
-- column keeps exactly that, as JSON ``{identity_pk, keywrap_pk, keywrap_sig,
-- gfs_url}`` (public keys and a server URL; no person data). NULL for every
-- other request.
--
-- CLAUDE.md "audit before a migration":
--
-- 1. Audited every path that touches join requests and peers: the paired
--    ``SPACE_JOIN_REQUEST`` path answers over the pairing
--    (``send_with_mesh_fallback``) — no keys needed; the §D2b invite-link
--    redeem seats a ``space_session`` row in ``remote_instances`` but only
--    once a token proved membership; ``remote_applicant_pk`` is the PERSON's
--    key, not the household's. Nothing keeps a stranger household's relay
--    contact while a request waits.
-- 2. Alternatives rejected: a ``space_session`` row in ``remote_instances``
--    at request time (would open the relay's inbound allow-list to a
--    household that is no member — the very thing a token gates); keeping it
--    in memory (a request answered after a restart could never be
--    delivered); asking the GFS again for the applicant's keys on approval
--    (a GFS lookup of any household's keys by id would undo the shielding).
-- 3. Smallest change: one NULL-defaulted column, no backfill, no index (it
--    is read by request id only, through the primary key).
ALTER TABLE space_join_requests ADD COLUMN applicant_relay TEXT;

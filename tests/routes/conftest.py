MakeClient = Callable[..., Awaitable[Any]]


@pytest.fixture
def make_client(aiohttp_client, tmp_dir) -> MakeClient:
    """Factory for the authenticated test client; ``client`` is
    ``await make_client()``. Pass ``overrides`` to swap app services for
    test doubles before the app starts (see :func:`override_app_on_startup`).
    """

    async def _make(overrides: AppOverrides | None = None):
        return await _authed_client(aiohttp_client, tmp_dir, overrides)

    return _make


async def client_with_stubs(
    request: pytest.FixtureRequest,
    make_client: MakeClient,
    stubs: Mapping[str, web.AppKey[Any]],
):
    """Build the module's ``client`` with each stub fixture the test asked
    for swapped in: ``stubs`` maps a fixture name to the app key it
    replaces. A module overrides ``client`` with this so a test written as
    ``async def test_x(client, stub)`` gets an app that started with the
    stub, whatever order pytest resolves the two fixtures in.
    """
    overrides = {
        key: request.getfixturevalue(name)
        for name, key in stubs.items()
        if name in request.fixturenames
    }
    return await make_client(overrides)


@pytest.fixture
async def client(make_client):
    """Authenticated test client using pytest-aiohttp (no TCP overhead).

    Identity is auto-generated by app startup via ``ensure_instance_identity``.
    Test reads the resulting public key from the DB to derive a matching
    admin user_id, then seeds a user + API token.
    """
    return await make_client()


async def _authed_client(aiohttp_client, tmp_dir, overrides: AppOverrides | None):
    cfg = Config(
        data_dir=str(tmp_dir),
        db_path=str(tmp_dir / "test.db"),
        media_path=str(tmp_dir / "media"),
        apps_path=str(tmp_dir / "apps"),
        mode="standalone",
        log_level="WARNING",
        db_write_batch_timeout_ms=10,
        # Seed [standalone].external_url so StandaloneAdapter.
        # get_federation_base() resolves — pairing route needs this.
        platform_options=MappingProxyType(
            {
                "standalone": MappingProxyType(
                    {"external_url": "https://test.example"},
                ),
            },
        ),
    )
    app = create_app(cfg)
    if overrides is not None:
        override_app_on_startup(app, overrides)
    tc = await aiohttp_client(ProductionLikeTestServer(app))

    db = app[_db_key]
    row = await db.fetchone(
        "SELECT identity_public_key FROM instance_identity WHERE id='self'"
    )
    pk_bytes = bytes.fromhex(row["identity_public_key"])
    uid = derive_user_id(pk_bytes, "admin")
    # ``INSERT OR REPLACE`` so the standalone adapter's first-boot admin
    # bootstrap (which seeds users.admin with a placeholder user_id)
    # doesn't collide with the test-derived ``uid``. The test still
    # gets the canonical user_id it expects in the row.
    await db.enqueue(
        "INSERT OR REPLACE INTO users(username, user_id, display_name, is_admin) "
        "VALUES(?,?,?,1)",
        ("admin", uid, "Admin"),
    )
    raw = "test-tok"
    await db.enqueue(
        "INSERT INTO api_tokens(token_id, user_id, label, token_hash) VALUES(?,?,?,?)",
        ("t1", uid, "t", sha256_token_hash(raw)),
    )
    tc._tok = raw
    tc._uid = uid
    tc._db = db
    tc._cfg = cfg
    return tc


def _auth(token: str) -> dict:
    return {"Authorization": f"Bearer {token}"}
